//! SQL (PostgreSQL DDL) and Mermaid `erDiagram` generators.

use crate::model::{Column, Project};

impl Project {
    /// Renders PostgreSQL-compatible `CREATE TABLE` + `ALTER TABLE … FOREIGN KEY`.
    pub fn to_sql(&self) -> String {
        let mut out = String::from("-- Generated by backers dbml\n\n");
        for table in &self.tables {
            out.push_str(&format!("CREATE TABLE {} (\n", table.name));
            let mut defs: Vec<String> = table
                .columns
                .iter()
                .map(|col| {
                    let mut def = format!("    {} {}", col.name, col.sql_type());
                    let constraints = col.sql_constraints();
                    if !constraints.is_empty() {
                        def.push(' ');
                        def.push_str(&constraints);
                    }
                    def
                })
                .collect();
            for index in &table.indexes {
                if index.unique {
                    defs.push(format!("    UNIQUE ({})", index.columns.join(", ")));
                }
            }
            out.push_str(&defs.join(",\n"));
            out.push_str("\n);\n\n");
        }
        for reference in &self.references {
            out.push_str(&format!(
                "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {}({});\n",
                reference.table2,
                reference.name,
                reference.column2,
                reference.table1,
                reference.column1,
            ));
        }
        out
    }

    /// Renders a Mermaid `erDiagram` block.
    pub fn to_mermaid(&self) -> String {
        let mut out = String::from("erDiagram\n\n");
        for table in &self.tables {
            out.push_str(&format!("    {} {{\n", table.name));
            for col in &table.columns {
                let key = if col.is_primary {
                    "PK "
                } else if col.is_unique {
                    "UK "
                } else {
                    ""
                };
                let not_null = if col.is_not_null { "NOT NULL " } else { "" };
                out.push_str(&format!(
                    "        {}{}{} {}\n",
                    key,
                    not_null,
                    col.sql_type(),
                    col.name
                ));
            }
            out.push_str("    }\n\n");
        }
        for reference in &self.references {
            out.push_str(&format!(
                "    {} ||--o{{ {} : \"{}\"\n",
                reference.table1, reference.table2, reference.name
            ));
        }
        out
    }
}

impl Column {
    /// Maps a DBML column type to a PostgreSQL type.
    pub fn sql_type(&self) -> String {
        let mapped = match self.typ.to_lowercase().as_str() {
            "int" | "integer" => "INTEGER",
            "bigint" => "BIGINT",
            "smallint" | "tinyint" => "SMALLINT",
            "serial" => "SERIAL",
            "bigserial" => "BIGSERIAL",
            "varchar" => "VARCHAR(255)",
            "text" => "TEXT",
            "char" => "CHAR(1)",
            "boolean" | "bool" => "BOOLEAN",
            "float" => "REAL",
            "double" => "DOUBLE PRECISION",
            "decimal" => "DECIMAL",
            "numeric" => "NUMERIC",
            "date" => "DATE",
            "time" => "TIME",
            "timestamp" => "TIMESTAMP",
            "timestamptz" => "TIMESTAMPTZ",
            "uuid" => "UUID",
            "json" => "JSON",
            "jsonb" => "JSONB",
            "blob" => "BLOB",
            "bytea" => "BYTEA",
            _ => return self.typ.to_uppercase(),
        };
        mapped.to_string()
    }

    /// Renders `PRIMARY KEY UNIQUE NOT NULL DEFAULT …` in order.
    pub fn sql_constraints(&self) -> String {
        let mut constraints: Vec<String> = Vec::new();
        if self.is_primary {
            constraints.push("PRIMARY KEY".to_string());
        }
        if self.is_unique && !self.is_primary {
            constraints.push("UNIQUE".to_string());
        }
        if self.is_not_null {
            constraints.push("NOT NULL".to_string());
        }
        if !self.default.is_empty() {
            let mut default = self.default.clone();
            let typ = self.typ.to_lowercase();
            if (typ.contains("char") || typ.contains("text") || typ.contains("enum"))
                && !default.starts_with('\'')
                && !default.starts_with('`')
            {
                default = format!("'{default}'");
            }
            constraints.push(format!("DEFAULT {default}"));
        }
        constraints.join(" ")
    }
}

/// Escapes the five XML entities used inside SVG text.
pub fn escape_xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('\'', "&apos;")
        .replace('"', "&quot;")
}
