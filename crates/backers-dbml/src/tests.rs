use super::*;

const SCHEMA: &str = r#"Project MyDatabase {
  Note: 'sample schema'
}

Table users {
  id integer [pk, increment]
  email varchar(255) [unique, not_null]
  name varchar(100) [not_null]
  created_at timestamp [not_null, default: `now()`]
  Note: 'User accounts'
}

Table posts {
  id integer [pk, increment]
  user_id integer [not_null, ref: > users.id]
  title varchar(200) [not_null]
  status varchar(20) [default: 'draft']
  indexes {
    (user_id)
  }
}

Enum post_status {
  draft
  published
}

Ref: user_posts users.id < posts.user_id
"#;

fn project() -> Project {
    parse(SCHEMA.as_bytes()).expect("parse")
}

#[test]
fn parses_tables_columns_and_project_name() {
    let p = project();
    assert_eq!(p.name, "MyDatabase");
    assert_eq!(p.tables.len(), 2);
    let users = p.get_table("users").expect("users table");
    assert_eq!(users.columns.len(), 4);
    assert!(users.comment.contains("User accounts"));
    let id = &users.columns[0];
    assert!(id.is_primary);
    assert!(id.settings.contains(&"increment".to_string()));
}

#[test]
fn parses_settings_flags_and_defaults() {
    let p = project();
    let email = p.get_column("users", "email").expect("email");
    assert!(email.is_unique && email.is_not_null && !email.is_primary);
    let created = p.get_column("users", "created_at").expect("created_at");
    assert_eq!(created.default, "now()");
}

#[test]
fn parses_inline_ref_and_top_level_ref() {
    let p = project();
    let user_id = p.get_column("posts", "user_id").expect("user_id");
    assert_eq!(user_id.ref_table, "users");
    assert_eq!(user_id.ref_column, "id");
    assert_eq!(p.references.len(), 1);
    let r = &p.references[0];
    assert_eq!(r.name, "user_posts");
    assert_eq!((r.table1.as_str(), r.table2.as_str()), ("users", "posts"));
}

#[test]
fn sql_output_has_ddl_constraints_and_fks() {
    let sql = project().to_sql();
    assert!(sql.contains("CREATE TABLE users ("));
    assert!(sql.contains("id INTEGER PRIMARY KEY"));
    assert!(sql.contains("email VARCHAR(255) UNIQUE NOT NULL"));
    assert!(sql.contains("DEFAULT 'draft'"));
    assert!(sql.contains(
        "ALTER TABLE posts ADD CONSTRAINT user_posts FOREIGN KEY (user_id) REFERENCES users(id);"
    ));
}

#[test]
fn mermaid_output_has_er_diagram() {
    let mmd = project().to_mermaid();
    assert!(mmd.starts_with("erDiagram"));
    assert!(mmd.contains("PK INTEGER id"));
    assert!(mmd.contains("users ||--o{ posts : \"user_posts\""));
}

#[test]
fn svg_output_is_a_standalone_document() {
    let svg = project().to_svg();
    assert!(svg.contains("<svg xmlns=\"http://www.w3.org/2000/svg\""));
    assert!(svg.contains("</svg>"));
    assert!(svg.contains(">users<"));
    assert!(svg.contains("enum post_status"));
}

#[test]
fn summary_is_json_with_tables_and_enums() {
    let summary = summary::summarize(&project()).expect("summarize");
    let value: serde_json::Value = serde_json::from_str(&summary).expect("json");
    assert_eq!(value["name"], "MyDatabase");
    assert_eq!(value["tables"][0]["name"], "users");
    assert_eq!(value["enums"][0]["name"], "post_status");
}

#[test]
fn empty_input_parses_to_empty_project() {
    let p = parse("".as_bytes()).expect("parse");
    assert!(p.tables.is_empty());
    assert!(p.to_sql().contains("-- Generated by backers dbml"));
}
